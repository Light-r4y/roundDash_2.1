#pragma once
#include <stdbool.h>
#include <stdint.h>

// Хранилище значений сигналов: развязка между источником (can_task или генератор
// "демо") и виджетами. Сигнал определяется именем из таблицы сигналов layout
// ("rpm", "speed"). Виджет получает id при сборке экрана и каждый такт читает
// значение; ничего не знает о том, откуда оно пришло.
//
// Значение живёт, пока его обновляют: у сигнала есть таймаут (мс), и если со времени
// последней записи прошло больше, roundGauge_signal_get() говорит "нет данных" -
// виджеты показывают "--". Таймаут 0 - не протухает.
//
// Запись и чтение float атомарны на ESP32-S3, блокировок на значения нет;
// регистрация имён идёт под спинлоком и редкая (при сборке экранов и смене таблицы).

#define RG_SIGNAL_NAME_MAX 16
#define RG_SIGNAL_MAX_COUNT 16

// Находит сигнал по имени или заводит новый. min/max - ожидаемый диапазон (нужен
// только генератору; при повторной регистрации обновляется). Возвращает id или
// -1, если таблица полна или имя пустое.
int roundGauge_signal_register(const char *name, float min, float max);

// Находит сигнал по имени или заводит новый с диапазоном 0..100, не трогая диапазон
// уже существующего. Для тех, кто пишет значения и диапазона не знает (can_task).
int roundGauge_signal_id(const char *name);

// Таймаут сигнала, мс (0 - не протухает). По умолчанию 0.
void roundGauge_signal_set_timeout(int id, uint32_t timeout_ms);

// Записать значение (из can_task); обновляет метку времени.
void roundGauge_signal_set(int id, float value);

// Прочитать значение. false - данных нет: не было записи или вышел таймаут.
bool roundGauge_signal_get(int id, float *out);

// Сбросить значение в "нет данных" (одного сигнала или всех).
void roundGauge_signal_invalidate(int id);
void roundGauge_signal_invalidate_all(void);

// Тестовый генератор ("демо"): пока включён, все зарегистрированные сигналы гоняются
// треугольной волной в своём диапазоне. Выключение сбрасывает значения.
void roundGauge_signal_sim_enable(bool enable);

// Шаг генератора; вызывать раз в такт из ui_task. Выключен - ничего не делает.
void roundGauge_signal_sim_step(uint32_t now_ms);
