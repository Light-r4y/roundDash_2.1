#pragma once
#include <stdint.h>

// Ориентация акселерометра в машине. Чистая математика без железа (проверяется тестом
// на хосте).
//
// Плата стоит как попало. Пока машина стоит ровно, акселерометр меряет только силу
// тяжести: вектор g0 (в g, в осях платы) направлен "вверх". Это даёт "вверх" при любом
// наклоне. "Вперёд" - одно из четырёх горизонтальных направлений, образованных двумя
// осями платы с наибольшей горизонтальной проекцией (плюс и минус каждой), выбирается
// номером 0..3 или определяется разгоном.
//
// Оси результата - как у машины: lon > 0 - ускорение вперёд, lat > 0 - ускорение
// вправо (правый поворот), vert > 0 - вверх. Вправо = вперёд x вверх.

// Единичный "вверх" u и четыре кандидата "вперёд" (горизонтальные единичные векторы):
// cand[0] = +ось A, cand[1] = -ось A, cand[2] = +ось B, cand[3] = -ось B, где A < B -
// индексы осей платы (0 X, 1 Y, 2 Z) с наибольшей горизонтальной проекцией.
void roundGauge_imu_basis(const float g0[3], float u[3], float cand[4][3]);

// Линейное ускорение a - g0 в осях машины для выбранного "вперёд" (0..3).
void roundGauge_imu_project(const float g0[3], uint8_t fwd, const float a[3], float *lon, float *lat, float *vert);

// Какой из четырёх кандидатов "вперёд" ближе всего к горизонтальной части вектора d
// (линейного ускорения a - g0): так "вперёд" определяется по разгону.
uint8_t roundGauge_imu_pick_forward(const float g0[3], const float d[3]);

// Горизонтальная часть вектора d (без составляющей вдоль "вверх") и её длина.
float roundGauge_imu_horizontal(const float g0[3], const float d[3], float h[3]);
